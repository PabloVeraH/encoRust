#[cfg(test)]
mod tests {
    use super::ANALYSIS_PROTOTYPE_FILTER;

    #[test]
    fn filter_table_checksum() {
        let mut xor: u64 = 0;
        let mut sum: u64 = 0;
        for &v in ANALYSIS_PROTOTYPE_FILTER.iter() {
            xor ^= v.to_bits() as u64;
            sum += v.to_bits() as u64;
        }
        // XOR + sum of all f32 bit patterns. Source: Shine tables.c
        // (commit 7e34e17), cross-checked against FFmpeg ff_mpa_enwindow.
        assert_eq!(
            xor, 0x0000_0000_3D12_8F19,
            "prototype filter XOR checksum mismatch"
        );
        assert_eq!(
            sum, 0x0000_00EF_147B_C2A7,
            "prototype filter SUM checksum mismatch"
        );
    }

    #[test]
    fn filter_is_not_zeroed() {
        let sum: f32 = ANALYSIS_PROTOTYPE_FILTER.iter().sum();
        assert!(
            sum.abs() > 0.001,
            "prototype filter appears zeroed (M2 not done)"
        );
    }
}
